// Command fontgen writes internal/render/fonts.go: the glyph metrics of the
// Adafruit GFX fonts the firmware draws with, so the server can measure text
// the way the board does. Run it with `go generate ./internal/render` after
// `make firmware` has fetched the GFX library.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// The fonts firmware/src/display.cpp uses, and their Go names.
var fonts = []struct{ file, name string }{
	{"FreeSans9pt7b", "sans9"},
	{"FreeSansBold9pt7b", "bold9"},
	{"FreeSansBold12pt7b", "bold12"},
	{"FreeSansBold18pt7b", "bold18"},
	{"FreeSansBold24pt7b", "bold24"},
}

// {bitmapOffset, width, height, xAdvance, xOffset, yOffset}
var glyphRe = regexp.MustCompile(`\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+)\s*\}`)

func main() {
	dir := flag.String("fonts", "", "the Adafruit GFX library's Fonts directory")
	out := flag.String("out", "fonts.go", "output file")
	flag.Parse()

	var b bytes.Buffer
	b.WriteString("// Code generated by fontgen from the Adafruit GFX fonts the firmware draws with; DO NOT EDIT.\n\n")
	b.WriteString("package render\n\n")
	b.WriteString("// Glyph metrics for characters 0x20 to 0x7E: width, x advance, x offset.\nvar (\n")
	for _, f := range fonts {
		src, err := os.ReadFile(filepath.Join(*dir, f.file+".h"))
		if err != nil {
			log.Fatal(err)
		}
		start := bytes.Index(src, []byte("Glyphs[]"))
		end := bytes.Index(src[start:], []byte("};"))
		if start < 0 || end < 0 {
			log.Fatalf("%s: no glyph table", f.file)
		}
		rows := glyphRe.FindAllStringSubmatch(string(src[start:start+end]), -1)
		if len(rows) != 95 {
			log.Fatalf("%s: %d glyphs, want 95", f.file, len(rows))
		}
		var g []string
		for _, r := range rows {
			g = append(g, fmt.Sprintf("{%s, %s, %s}", r[2], r[4], r[5]))
		}
		fmt.Fprintf(&b, "\t%s = font{%q, [95]glyph{%s}}\n", f.name, f.file, strings.Join(g, ", "))
	}
	b.WriteString(")\n")
	code, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
}
